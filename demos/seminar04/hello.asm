; BIOS запускает этот сектор дискеты по физическому адресу 0000:7C00.
; Сохраните сообщение коротким, чтобы вместе с кодом занять не более 510 байтов.
bits 16                       ; инструкции для 16-битного real mode
org 0x7c00                    ; NASM считает смещения от адреса загрузки

start:
    cli                       ; не принимать IRQ, пока настраиваем стек
    xor ax, ax                ; AX=0
    mov ds, ax                ; DS=0, сегмент строки в этом секторе
    mov ss, ax                ; SS=0, сегмент стека
    mov sp, 0x7c00            ; вершина стека ниже загрузочного сектора
    sti                       ; снова разрешить IRQ
    cld                       ; lodsb будет увеличивать SI
    mov ax, 0x0003            ; BIOS: установить текстовый режим 80×25
    int 0x10                  ; очистить экран и поставить курсор в начало
    mov si, message           ; DS:SI указывает на первый байт строки
.next:
    lodsb                     ; взять очередной байт строки в AL; SI += 1
    test al, al               ; нулевой ли это конец строки?
    jz .halt                  ; да: перейти к остановке
    mov ah, 0x0e              ; функция BIOS «вывести один символ»
    mov bx, 0x0007            ; BH=0: первая страница, BL=07h
    int 0x10                  ; BIOS печатает символ из AL
    jmp .next                 ; повторить для следующего байта
.halt:
    cli                       ; остановить выполнение без IRQ
    hlt                       ; CPU ждёт внешнего события
    jmp .halt                 ; если продолжился, остановить снова

message: db 'HELLO BIOS', 0   ; ASCII-строка завершается нулевым байтом
times 510 - ($ - $$) db 0    ; нули до последних двух байтов сектора
dw 0xaa55                     ; x86 little-endian: байты 55 AA для BIOS
