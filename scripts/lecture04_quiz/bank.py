def day_questions(day, lab):
    if day not in range(1, 6) or lab not in LAB:
        raise ValueError('Неизвестный день или вариант лабораторной')
    return tuple(q for q in COMMON if q.day in (None, day)) + tuple(
        q for q in LAB[lab] if q.day in (None, day))


def validate_bank():
    questions = COMMON + sum((pool for pool in LAB.values()), ())
    if len(questions) != 42 or len({q.id for q in questions}) != len(questions):
        raise ValueError('Банк должен содержать 42 вопроса с уникальными ID')
    for question in questions:
        if (len(question.options) != 4 or len(set(question.options)) != 4
                or question.correct not in range(4) or not question.prompt.strip()
                or any(not option.strip() for option in question.options)):
            raise ValueError(f'Некорректный вопрос {question.id}')
    for lab in LAB:
        for day in range(1, 6):
            questions = day_questions(day, lab)
            if len(questions) != 10 or sum(q.id.startswith('G') for q in questions) != 6:
                raise ValueError(f'Неполный набор: день {day}, лабораторная {lab}')
            for other_day in range(1, day):
                if len({q.id for q in questions} & {q.id for q in day_questions(other_day, lab)}) != 5:
                    raise ValueError('Между днями должны повторяться ровно пять вопросов')
